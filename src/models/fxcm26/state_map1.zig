/// `cs = cs*1000003 + (u32)pr` over every `pr` produced (all configs).
const PR_CS: u64 = 3491727857752600288;

/// `cs = cs*1000003 + t[i]` over the final `t[]` of every config.
const T_CS: u64 = 6316962684870258394;

fn xs(s: *u32) u32 {
    s.* ^= s.* << 13;
    s.* ^= s.* >> 17;
    s.* ^= s.* << 5;
    return s.*;
}

test "matches_cpp_oracle" {
    const allocator = std.testing.allocator;

    // Build the shared decay table dt[i] = 4096/(i+2), dt[1023]=1 (mirrors Tables).
    const Tables = struct { dt: [1024]i32 };
    var tables: Tables = undefined;
    for (0..1024) |i| {
        tables.dt[i] = @divTrunc(4096, @as(i32, @intCast(i)) + 2);
    }
    tables.dt[1023] = 1;

    // Must mirror oracle.cpp's `cfgs` exactly.
    const Cfg = struct { n: usize, lim: i32, seed: u32, steps: usize };
    const cfgs = [_]Cfg{
        .{ .n = 256, .lim = 255, .seed = 0x0001_2345, .steps = 100_000 },
        .{ .n = 1024, .lim = 1023, .seed = 0x0000_BEEF, .steps = 100_000 },
        .{ .n = 16, .lim = 8, .seed = 0x0000_CAFE, .steps = 50_000 },
        .{ .n = 4096, .lim = 511, .seed = 0x00AB_CDEF, .steps = 100_000 },
    };

    var pr_cs: u64 = 0;
    var t_cs: u64 = 0;
    var samples = std.ArrayList(i32){};
    defer samples.deinit(allocator);

    for (cfgs) |cfg| {
        var sm = try StateMap1.new(allocator, cfg.n, cfg.lim);
        defer sm.deinit(allocator);
        var s = cfg.seed;
        var step: usize = 0;
        while (step < cfg.steps) : (step += 1) {
            const v = xs(&s);
            const y: i32 = @intCast(v & 1);
            const c: i32 = @bitCast(v >> 1);
            const pr = sm.set(&tables, y, c);
            pr_cs = pr_cs *% 1000003 +% @as(u64, @as(u32, @bitCast(pr)));
            if (step < 24 or step % 9999 == 0) {
                try samples.append(allocator, pr);
            }
        }
        for (sm.t) |val| {
            t_cs = t_cs *% 1000003 +% @as(u64, val);
        }
    }

    try std.testing.expectEqualSlices(i32, PR_SAMPLES[0..], samples.items);
    try std.testing.expectEqual(PR_CS, pr_cs);
    try std.testing.expectEqual(T_CS, t_cs);
}
