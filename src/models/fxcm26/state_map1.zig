//! `StateMap1` — port of `struct StateMap1` (`fxcmv1.cpp:707-736`), translated
//! 1:1 from `state_map1.rs`.
//!
//! A count-limited, learning-rate-decayed StateMap. Each context slot packs a
//! 20-bit prediction in the high bits and a 10-bit hit count in the low bits of a
//! `u32`. `set(c)` first runs `update` against the *previous* context using the
//! latched bit `y`, then latches the new context `c & mask` and returns its
//! 12-bit prediction (`t >> 20`).
//!
//! Faithfulness notes (vs the C++/Rust):
//! - `dt[n]` is the shared decay table (`4096/(n+2)`, `dt[1023]=1`) — threaded in
//!   via `Tables` (the C++ used the file-global `dt`). We keep the `tables`
//!   parameter (typed `anytype`) reading `tables.dt[...]`, so both the real
//!   `tables.zig` `Tables` and the self-contained test struct work; this keeps
//!   the module independently testable while matching the Rust signature shape.
//! - The blend term `((y<<20)-pr1)*dt[n]+512` is computed in 32-bit signed
//!   arithmetic; the product can overflow `i32` at the boundary (e.g. `n==0`,
//!   `pr1==0`, `y==1` gives `2^31`). C++ wraps (2's-complement), so we use
//!   wrapping `*%`/`+%` and `@bitCast` to `u32` before the `& 0xfffffc00` mask,
//!   exactly matching the implicit `int -> unsigned` of the `0xfffffc00` literal.
//! - `>>` on `pr1`/`pr` reads from a `u32`, so the shifts are logical.

const std = @import("std");

pub const StateMap1 = struct {
    /// `cxt -> (prediction << 12) | count`, packed into a `u32`.
    t: []u32,
    /// Context of the last prediction (index into `t`).
    cxt: usize,
    /// Last 12-bit prediction returned by `set`.
    pr: i32,
    /// `n - 1`; ANDs the incoming context into range.
    mask: i32,
    /// Maximum count used for the decay (`1..=1023`).
    limit: i32,

    /// `StateMap1::Init(n, lim)`. `n` must be a power of two; `0 < lim < 1024`.
    pub fn new(allocator: std.mem.Allocator, n: usize, limit: i32) !StateMap1 {
        std.debug.assert(std.math.isPowerOfTwo(n)); // "n must be a power of two"
        std.debug.assert(limit > 0 and limit < 1024); // "limit must be in 1..1024"
        const t = try allocator.alloc(u32, n);
        @memset(t, @as(u32, 1) << 31);
        return StateMap1{
            .t = t,
            .cxt = 0,
            .pr = 2048,
            .mask = @as(i32, @intCast(n)) - 1,
            .limit = limit,
        };
    }

    pub fn deinit(self: *StateMap1, allocator: std.mem.Allocator) void {
        allocator.free(self.t);
        self.t = &[_]u32{};
    }

    /// `StateMap1::update` — blend the latched bit `y` into the current context.
    inline fn update(self: *StateMap1, tables: anytype, y: i32) void {
        std.debug.assert(y == 0 or y == 1);
        const p0 = self.t[self.cxt];
        const n: i32 = @intCast(p0 & 1023); // count
        const pr1: i32 = @intCast(p0 >> 12); // 20-bit prediction
        var np = p0;
        if (n < self.limit) {
            np = np +% 1;
        }
        // ((y<<20)-pr1)*dt[n]+512, 32-bit signed (may wrap), then mask low 10 bits.
        const term_i: i32 = ((y << 20) - pr1) *% tables.dt[@as(usize, @intCast(n))] +% 512;
        const term: u32 = @as(u32, @bitCast(term_i)) & 0xffff_fc00;
        np = np +% term;
        self.t[self.cxt] = np;
    }

    /// `StateMap1::set(c)` — update against the previous context with `y`, latch the
    /// new context `c & mask`, and return its 12-bit prediction.
    pub inline fn set(self: *StateMap1, tables: anytype, y: i32, c: i32) i32 {
        self.update(tables, y);
        self.cxt = @intCast(c & self.mask);
        self.pr = @intCast(self.t[self.cxt] >> 20);
        return self.pr;
    }

    /// Current latched prediction. (Rust name: `pr`; renamed to avoid the
    /// Zig field/decl name collision with field `pr`.)
    pub inline fn get_pr(self: *const StateMap1) i32 {
        return self.pr;
    }
};

