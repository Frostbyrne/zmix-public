//! `APM` — Adaptive Probability Map, port of `template<int S> struct APM`
//! (`fxcmv1.cpp:1622-1643`), translated 1:1 from `apm.rs`.
//!
//! An APM refines an input probability `pr` (12-bit, 0..4095) given a context
//! `cxt` (0..N-1). It keeps, per context, a 33-point piecewise-linear table over
//! the *stretched* probability axis. `p` first nudges the two table points that
//! the previous call interpolated between toward the just-seen bit `y`, then
//! latches the new `(pr, cxt)` and returns the interpolated 16-bit table value
//! shifted back down to a 12-bit probability.
//!
//! Faithfulness notes (vs the C++ / Rust):
//! - `squash`/`stretch` come from `tables.zig` (the C++ used the file-global
//!   `sqt`/`strt` tables). `stretch(pr)` indexes `strt[pr]`, so `pr` **must** be
//!   in `0..=4095`.
//! - `t[i]` is a `u16`; the learning update `t += (g - t) >> rate` is computed in
//!   32-bit signed and stored back truncated to 16 bits — replicated with `i32`
//!   math and a final low-16-bit truncation (matching Rust `as u16`).
//! - `>>` on the signed update and on the final blend is arithmetic (Zig `>>` on a
//!   signed type is arithmetic, matching g++/Rust here).
//! - `w = pr & 127` uses the *stretched* (possibly negative) `pr`; the low-7-bit
//!   mask on a two's-complement value matches between C and Rust.
//! - `index` carries across calls (the table points to refine next time); `new`
//!   seeds it to 0 so the first call refines `t[0]`/`t[1]`.

const std = @import("std");
const Tables = @import("tables.zig").Tables;

pub const Apm = struct {
    /// Index (into `t`) of the lower of the two points the last `p` blended.
    index: usize,
    /// `[N][33]`: stretched-prob bucket -> 16-bit-scaled probability.
    t: []u16,
    /// Number of contexts (`S` in the C++ template).
    n: usize,

    /// `APM<n>::Init`. Seeds every context's 33-point row to
    /// `squash((j-16)*128)*16`.
    pub fn new(a: std.mem.Allocator, tables: *const Tables, n: usize) !Apm {
        std.debug.assert(n >= 1); // APM needs at least one context
        const t = try a.alloc(u16, n * 33);
        @memset(t, 0);
        var j: i32 = 0;
        while (j < 33) : (j += 1) {
            t[@intCast(j)] = @intCast(tables.squash((j - 16) * 128) * 16);
        }
        var i: usize = 33;
        while (i < n * 33) : (i += 1) {
            t[i] = t[i - 33];
        }
        return Apm{ .index = 0, .t = t, .n = n };
    }

    pub fn deinit(self: *Apm, a: std.mem.Allocator) void {
        a.free(self.t);
    }

    /// `APM::p(pr, cxt, rate, y)` — refine `pr` in context `cxt`, learning from `y`.
    ///
    /// `pr` must be in `0..=4095` (it indexes the stretch table). `cxt` must be in
    /// `0..n`. `y` is the bit just observed (0/1). Returns a 12-bit probability.
    pub fn p(self: *Apm, tables: *const Tables, pr_in: i32, cxt: i32, rate: i32, y: i32) i32 {
        std.debug.assert(pr_in >= 0 and pr_in <= 4095);
        std.debug.assert(cxt >= 0 and @as(usize, @intCast(cxt)) < self.n);
        std.debug.assert(y == 0 or y == 1);

        const pr: i32 = @as(i32, tables.stretch(pr_in));
        const g: i32 = (y << 16) + (y << @as(u5, @intCast(rate))) - y * 2;

        // Refine the two points latched by the previous call (or t[0]/t[1] init).
        const lo = self.index;
        const cur0: i32 = @as(i32, self.t[lo]);
        self.t[lo] = @truncate(@as(u32, @bitCast(cur0 + ((g - cur0) >> @as(u5, @intCast(rate))))));
        const cur1: i32 = @as(i32, self.t[lo + 1]);
        self.t[lo + 1] = @truncate(@as(u32, @bitCast(cur1 + ((g - cur1) >> @as(u5, @intCast(rate))))));

        const w: i32 = pr & 127; // interpolation weight (33 points)
        const index: usize = @as(usize, @intCast((pr + 2048) >> 7)) + @as(usize, @intCast(cxt)) * 33;
        self.index = index;

        return (@as(i32, self.t[index]) * (128 - w) + @as(i32, self.t[index + 1]) * w) >> 11;
    }
};

