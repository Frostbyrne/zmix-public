fn xs(s: *u32) u32 {
    s.* ^= s.* << 13;
    s.* ^= s.* >> 17;
    s.* ^= s.* << 5;
    return s.*;
}

const RATES = [_]i32{ 3, 6, 7, 8, 9 };

test "matches_cpp_oracle" {
    const a = std.testing.allocator;
    var tables = try Tables.new(a);
    defer tables.deinit(a);

    // Must mirror oracle.cpp's drivecalls exactly: (n, seed, steps).
    const Cfg = struct { n: usize, seed: u32, steps: usize };
    const cfgs = [_]Cfg{
        .{ .n = 256, .seed = 0x0001_2345, .steps = 100_000 },
        .{ .n = 33, .seed = 0x0000_BEEF, .steps = 60_000 },
        .{ .n = 1024, .seed = 0x00AB_CDEF, .steps = 100_000 },
        .{ .n = 2, .seed = 0x0000_CAFE, .steps = 40_000 },
    };

    var pr_cs: u64 = 0;
    var t_cs: u64 = 0;
    var samples = std.ArrayList(i32){};
    defer samples.deinit(a);

    for (cfgs) |cfg| {
        var ap = try Apm.new(a, &tables, cfg.n);
        defer ap.deinit(a);
        var s = cfg.seed;
        var step: usize = 0;
        while (step < cfg.steps) : (step += 1) {
            const v = xs(&s);
            const pr: i32 = @intCast(v & 4095);
            const cxt: i32 = @intCast((v >> 12) % @as(u32, @intCast(cfg.n)));
            const y: i32 = @intCast((v >> 24) & 1);
            const rate = RATES[@intCast((v >> 25) % 5)];
            const out = ap.p(&tables, pr, cxt, rate, y);
            pr_cs = pr_cs *% 1000003 +% @as(u64, @as(u32, @bitCast(out)));
            if (step < 24 or step % 9999 == 0) {
                try samples.append(a, out);
            }
        }
        for (ap.t) |vv| {
            t_cs = t_cs *% 1000003 +% @as(u64, vv);
        }
    }

    try std.testing.expectEqualSlices(i32, PR_SAMPLES[0..], samples.items);
    try std.testing.expectEqual(PR_CS, pr_cs);
    try std.testing.expectEqual(T_CS, t_cs);
}
